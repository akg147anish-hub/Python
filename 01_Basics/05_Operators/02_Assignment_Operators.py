number = 10

print("Initial Value:", number)

number += 5
print("After += 5:", number)

number -= 3
print("After -= 3:", number)

number *= 2
print("After *= 2:", number)

number /= 4
print("After /= 4:", number)

number //= 2
print("After //= 2:", number)

number %= 3
print("After %= 3:", number)

number **= 2
print("After **= 2:", number)