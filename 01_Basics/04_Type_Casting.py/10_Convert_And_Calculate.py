"""
Question:
Take two numbers as strings, convert them into integers,
and calculate their sum, difference and product.
"""

num1 = input("Enter first number: ")
num2 = input("Enter second number: ")

num1 = int(num1)
num2 = int(num2)

print("Sum:", num1 + num2)
print("Difference:", num1 - num2)
print("Product:", num1 * num2)